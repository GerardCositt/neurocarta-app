            <p>Los impuestos aplicables se calculan conforme a la normativa vigente, la residencia fiscal del usuario, la naturaleza del servicio y los datos facilitados durante la contratación.</p>

            <p>NeuroCarta no será responsable de errores de facturación derivados de datos fiscales incorrectos, incompletos o desactualizados proporcionados por el usuario.</p>

