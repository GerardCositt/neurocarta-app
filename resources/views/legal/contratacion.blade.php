            <p>NeuroCarta podrá ofrecer promociones, descuentos, cupones, períodos de prueba, créditos gratuitos o condiciones especiales de lanzamiento.</p>

            <p>Dichas promociones tendrán la duración, límites y condiciones indicadas en cada caso, y podrán estar sujetas a restricciones por usuario, cuenta, establecimiento, territorio, fecha, método de pago o tipo de plan.</p>

