            <p>Cuando el usuario contrate actuando como empresario, profesional, sociedad, autónomo o en el marco de una actividad económica, no resultará aplicable el derecho de desistimiento previsto para consumidores y usuarios.</p>

            <h2>13. Política de devoluciones</h2>

            <p>Salvo que legalmente corresponda, los importes abonados por períodos de suscripción ya iniciados, servicios ya prestados, configuraciones realizadas, créditos consumidos o trabajos personalizados no serán reembolsables.</p>

            <p>En caso de error técnico imputable a NeuroCarta que impida de forma sustancial la prestación del servicio contratado, NeuroCarta podrá optar, según corresponda, por subsanar la incidencia, ampliar razonablemente el período de servicio, repetir la prestación, devolver créditos consumidos o realizar un reembolso proporcional.</p>

            <p>No procederá devolución cuando la incidencia derive de errores del usuario, falta de información, datos incorrectos, uso indebido, incumplimiento de estas condiciones, problemas ajenos a NeuroCarta o falta de uso del servicio por parte del usuario.</p>

            <h2>14. Impagos, devoluciones de cargos e incidencias de cobro</h2>

            <p>En caso de impago, tarjeta rechazada, devolución de recibos, cancelación indebida de cargos, fraude, disputa injustificada, falta de actualización del método de pago o cualquier incidencia de cobro, NeuroCarta podrá suspender total o parcialmente el acceso a las funcionalidades de pago.</p>

            <p>La suspensión podrá afectar, entre otros aspectos, a la edición de la carta, publicación de cambios, uso de IA, acceso al panel, disponibilidad pública de la carta, soporte, almacenamiento o cualquier funcionalidad asociada al plan contratado.</p>

            <p>NeuroCarta podrá intentar nuevos cargos sobre el método de pago facilitado, solicitar la actualización de los datos de pago o reclamar las cantidades pendientes.</p>

            <p>Los gastos bancarios, comisiones, costes de devolución, recargos o perjuicios derivados de una incidencia de cobro imputable al usuario podrán ser repercutidos cuando legalmente proceda.</p>

