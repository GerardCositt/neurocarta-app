            <p>El usuario podrá cancelar la renovación de su suscripción conforme al procedimiento disponible en la Plataforma o solicitándolo a través de los canales de contacto habilitados por NeuroCarta.</p>

            <p>La cancelación impedirá futuras renovaciones, pero no implicará automáticamente la devolución de los importes ya abonados por períodos de servicio iniciados, salvo que legalmente corresponda o NeuroCarta lo acepte expresamente.</p>

            <p>Tras la cancelación, el usuario podrá seguir accediendo a las funcionalidades contratadas hasta la finalización del período ya abonado, salvo en casos de incumplimiento grave, impago, uso fraudulento o suspensión conforme a estas condiciones.</p>

            <p>Una vez finalizado el período contratado, la cuenta podrá quedar limitada, suspendida, degradada a un plan gratuito si existiese, o desactivada, de acuerdo con las condiciones del servicio vigentes.</p>

