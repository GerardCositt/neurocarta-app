            <h2>2. Objeto de las Condiciones de Contratación</h2>

            <p>Estas condiciones regulan los aspectos económicos y comerciales derivados de la contratación de NeuroCarta, incluyendo planes de suscripción, servicios premium, créditos de inteligencia artificial, ampliaciones, renovaciones, cancelaciones, facturación, impagos y, en su caso, derecho de desistimiento.</p>

            <p>Las presentes condiciones se aplican a usuarios que contraten NeuroCarta actuando como empresarios, profesionales, sociedades, autónomos, establecimientos de hostelería o representantes autorizados de un negocio. Si excepcionalmente contratase una persona consumidora, se aplicarán además los derechos que le reconozca la normativa de consumidores y usuarios.</p>

            <h2>3. Servicios contratables</h2>

            <p>NeuroCarta puede ofrecer distintos servicios de pago, entre ellos planes de suscripción, servicios de configuración inicial, funcionalidades avanzadas, créditos para inteligencia artificial, servicios de importación de carta, generación o mejora de imágenes, traducciones, personalizaciones, soporte adicional u otros servicios complementarios.</p>

            <p>Las funcionalidades incluidas en cada servicio serán las indicadas en la página de precios, en la propuesta comercial, en el panel de contratación o en las condiciones particulares aceptadas por el usuario en el momento de la contratación.</p>

            <p>NeuroCarta podrá modificar, ampliar, sustituir o eliminar funcionalidades de los planes cuando sea necesario por motivos técnicos, legales, de seguridad, operativos o de evolución del producto, sin perjuicio de respetar las condiciones económicas vigentes durante el período ya contratado cuando legalmente proceda.</p>

            <h2>4. Planes, precios y límites de uso</h2>

            <p>NeuroCarta podrá ofrecer distintos planes con precios, límites y funcionalidades diferentes. A título orientativo, la Plataforma podrá comercializar planes con importes de 69 euros, 35 euros y 25 euros, sin perjuicio de que los precios vigentes sean siempre los publicados en la Plataforma o en la propuesta comercial aplicable en el momento de la contratación.</p>

            <p>Cada plan podrá establecer límites respecto al número de cartas, productos, categorías, idiomas, establecimientos, usuarios, códigos QR, almacenamiento, imágenes, créditos de inteligencia artificial, personalizaciones, soporte, funcionalidades avanzadas o cualquier otra capacidad del servicio.</p>

            <p>El usuario deberá revisar las características, límites, precio final, periodicidad, impuestos y condiciones de renovación antes de confirmar la contratación.</p>

            <p>Los precios podrán mostrarse con o sin impuestos en función del tipo de cliente, país, configuración fiscal y normativa aplicable. Antes de confirmar el pago, se mostrará el precio final o la información necesaria para conocerlo.</p>

            <h2>5. Proceso de contratación electrónica</h2>

            <p>La contratación podrá realizarse a través de la Plataforma, mediante enlace de pago, propuesta comercial, formulario de alta, panel de cliente, pasarela de pago o cualquier otro medio habilitado por NeuroCarta.</p>

            <p>Antes de finalizar la contratación, el usuario deberá revisar el plan o servicio seleccionado, el precio, los impuestos aplicables, la periodicidad, las funcionalidades incluidas, las condiciones de renovación y los datos fiscales o de facturación introducidos.</p>

            <p>La contratación se entenderá perfeccionada cuando el usuario confirme la compra o suscripción y el pago sea aceptado por el proveedor de pago correspondiente, salvo que se pacte expresamente otro momento de activación en una propuesta comercial.</p>

            <p>Tras la contratación, NeuroCarta podrá enviar una confirmación al correo electrónico facilitado por el usuario, sin perjuicio de que la información de la cuenta también pueda estar disponible dentro de la Plataforma.</p>

            <h2>6. Medios de pago</h2>

            <p>Los pagos podrán realizarse mediante tarjeta bancaria, pasarela de pago, Stripe u otros medios de pago habilitados en cada momento por NeuroCarta.</p>

            <p>Cuando el pago se tramite a través de un proveedor externo, el usuario acepta que dicho proveedor pueda procesar la operación conforme a sus propias condiciones y políticas de seguridad.</p>

            <p>NeuroCarta no almacena necesariamente los datos completos de la tarjeta bancaria del usuario. Dichos datos podrán ser gestionados directamente por el proveedor de pago certificado que intervenga en la operación.</p>

            <p>El usuario garantiza que está autorizado para utilizar el método de pago facilitado y que los datos de pago son válidos, exactos y están actualizados.</p>

            <h2>7. Suscripciones, renovación automática y periodicidad</h2>

            <p>Salvo que se indique expresamente lo contrario, los planes de NeuroCarta podrán contratarse bajo modalidad de suscripción recurrente mensual, anual u otra periodicidad indicada en el momento de la contratación.</p>

            <p>Las suscripciones se renovarán automáticamente por períodos sucesivos equivalentes al inicialmente contratado, salvo que el usuario solicite la cancelación 30 días antes de la fecha de renovación conforme al procedimiento habilitado en la Plataforma o comunicado por NeuroCarta.</p>

            <p>El usuario autoriza a NeuroCarta o a sus proveedores de pago a cargar de forma recurrente los importes correspondientes a la suscripción, renovación, ampliaciones, créditos o servicios contratados mediante el método de pago facilitado.</p>

            <p>La falta de uso de la Plataforma durante un período de suscripción activo no dará derecho, por sí sola, a la devolución total o parcial del importe abonado.</p>

            <h2>8. Cambios de plan, ampliaciones y reducciones</h2>

            <p>El usuario podrá solicitar cambios de plan, ampliaciones, reducciones o servicios adicionales conforme a las opciones disponibles en la Plataforma o mediante solicitud a NeuroCarta.</p>

            <p>En caso de mejora de plan o contratación de ampliaciones, NeuroCarta podrá cobrar la diferencia correspondiente de forma inmediata o prorrateada, según se indique en el momento de la modificación.</p>

            <p>En caso de reducción de plan, la modificación podrá aplicarse al finalizar el período de facturación en curso, salvo que NeuroCarta indique expresamente otra fecha de efecto.</p>

            <p>La reducción de plan puede implicar la pérdida, bloqueo o limitación de funcionalidades, capacidad, almacenamiento, productos, idiomas, usuarios, créditos o configuraciones asociadas al plan superior.</p>

            <h2>9. Créditos de inteligencia artificial</h2>

            <p>NeuroCarta podrá ofrecer un sistema de créditos, saldo o bonos para el uso de funcionalidades de inteligencia artificial, tales como generación de imágenes, mejora de imágenes, importación asistida de carta, generación de descripciones, traducciones, sugerencias comerciales u otras acciones asistidas por IA.</p>

            <p>Cada acción de IA podrá consumir un número determinado de créditos, que será informado en la Plataforma antes de ejecutar la acción cuando resulte aplicable, especialmente en operaciones masivas o de coste variable.</p>

            <p>El usuario deberá confirmar las acciones de IA que impliquen consumo de créditos. Una vez ejecutada correctamente la acción, los créditos consumidos no serán reembolsables, salvo error técnico imputable a NeuroCarta o salvo que se indique expresamente lo contrario.</p>

            <p>Si una acción de IA falla por causa técnica no imputable al usuario y no se obtiene el resultado contratado, NeuroCarta podrá devolver los créditos consumidos, repetir la operación sin coste adicional o aplicar la solución técnica razonable que corresponda.</p>

            <p>Los créditos podrán tener condiciones específicas de caducidad, uso mínimo, no transferibilidad, limitaciones por cuenta o restricciones de acumulación, que serán informadas en la Plataforma o en la propuesta correspondiente.</p>

            <p>Los créditos no son canjeables por dinero ni transferibles entre cuentas, salvo autorización expresa de NeuroCarta.</p>

